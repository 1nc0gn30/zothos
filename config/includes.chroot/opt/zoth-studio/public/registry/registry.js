/* ---------- data sources ----------
   The hub is served by a plain static file server (or a CDN in front of
   public/): every URL a page fetches has to be a real file on disk. There is
   no application server and no function runtime here, so a request to a
   bare /api/tools (live orchestrator path) is guaranteed to 404 and to log a
   console error on every load. Source order is therefore:

     1. /api/tools.json  - the static registry endpoint committed under
        public/api/ (generated by scripts/generate-tools-json.py). Preferred.
     2. /registry/tools.json - the older committed snapshot. Fallback.
     3. window.ZOTH_TOOLS_LIVE_API - an explicit live orchestrator, only when a
        host injects it. Never probed by default: a path we know is absent must
        not be requested, because the 404 is the defect.
     4. an honest, visible empty state.

   Every failure path is handled: no unhandled rejection, no console noise. */


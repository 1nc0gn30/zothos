function setSource(label, live) {
  const el = $("src");
  if (!el) return;
  el.textContent = label;
  el.classList.toggle("is-live", !!live);
}

async function readToolList(url, init) {
  const r = await fetch(url, init);
  if (!r.ok) throw new Error(`${url} -> HTTP ${r.status}`);
  const j = await r.json();
  const tools = Array.isArray(j) ? j : j && j.tools;
  if (!Array.isArray(tools)) throw new Error(`${url} -> payload has no tools[]`);
  return tools;
}


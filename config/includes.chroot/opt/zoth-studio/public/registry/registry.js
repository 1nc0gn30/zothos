async function loadSnapshot() {
  const tools = await readToolList(STATIC_ENDPOINT, { cache: "no-store" });
  all = redact(tools);
  setSource("registry endpoint", false);
}

async function probeLive() {
  /* Only ever runs against an endpoint the host explicitly configured. */
  if (!LIVE_ENDPOINT) return;
  try {
    const ctrl = new AbortController();
    const t = setTimeout(() => ctrl.abort(), 800);
    const tools = await readToolList(LIVE_ENDPOINT, {
      cache: "no-store",
      signal: ctrl.signal,
    });
    clearTimeout(t);
    if (!tools.length) return;
    all = redact(tools);
    setSource("live deck", true);
    renderCats();
    layoutWall();
  } catch {
    /* static data stands */
  }
}

function visibleList() {
  const q = query.trim().toLowerCase();
  return all.filter((t) => {
    if (filterCat !== "all" && t.category !== filterCat) return false;
    if (!q) return true;
    return `${t.name} ${t.description} ${t.category} ${(t.tags || []).join(" ")} ${t.id}`
      .toLowerCase()
      .includes(q);
  });
}

function wallList() {
  const list = visibleList();
  if (query.trim() || list.length <= 36) return list;
  const byCat = new Map();
  list.forEach((t) => {
    if (!byCat.has(t.category)) byCat.set(t.category, []);
    byCat.get(t.category).push(t);
  });
  const cats = [...byCat.keys()];
  const picked = [];
  let i = 0;
  while (picked.length < 36) {
    let added = false;
    for (const c of cats) {
      const t = byCat.get(c)[i];
      if (t) {
        picked.push(t);
        added = true;
      }
      if (picked.length >= 36) break;
    }
    if (!added) break;
    i += 1;
  }
  return picked;
}

function renderCats() {
  const counts = new Map();
  all.forEach((t) => counts.set(t.category, (counts.get(t.category) || 0) + 1));
  const names = [...counts.keys()].sort((a, b) => counts.get(b) - counts.get(a));
  $("cats").replaceChildren();
  const mk = (id, label) => {
    const b = document.createElement("button");
    b.type = "button";
    b.setAttribute("role", "tab");
    b.textContent = label;
    b.setAttribute("aria-selected", filterCat === id ? "true" : "false");
    b.classList.toggle("is-on", filterCat === id);
    b.addEventListener("click", () => {
      filterCat = id;
      renderCats();
      layoutWall();
    });
    return b;
  };
  $("cats").append(mk("all", `All ${all.length}`));
  names.forEach((n) => $("cats").append(mk(n, `${n.split("&")[0].trim()} ${counts.get(n)}`)));
}

